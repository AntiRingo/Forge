import {chromium} from 'playwright';import {mkdir,writeFile} from 'node:fs/promises';import assert from 'node:assert/strict';
await mkdir('qa',{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true,args:['--enable-unsafe-swiftshader','--disable-gpu-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://127.0.0.1:5173',{waitUntil:'networkidle'});
await page.screenshot({path:'qa/desktop-prepare.png',fullPage:true});
await page.locator('#start').click();
await page.locator('#cast').waitFor({state:'visible'});
await page.waitForFunction(()=>!document.querySelector('#cast').disabled,{},{timeout:45000});
await page.locator('#cast').click();
await page.screenshot({path:'qa/desktop-forging.png',fullPage:true});
for(let i=0;i<4;i++){await page.locator('#strike').click();await page.waitForTimeout(500);}
await page.reload({waitUntil:'networkidle'});
assert.ok(await page.locator('#strike').isVisible(),'in-progress session must survive reload');
await page.locator('#finish').click();
await page.screenshot({path:'qa/desktop-finished.png',fullPage:true});
await page.locator('#keep').click();
await page.locator('[data-tab=collection]').click();assert.equal(await page.locator('[data-sell]').count(),1);
await page.locator('[data-sell]').click();
await page.locator('[data-tab=market]').click();
await page.locator('#mine').click();
await page.locator('[data-buy=iron]').click();
await page.screenshot({path:'qa/desktop-market.png',fullPage:true});
await page.locator('[data-tab=upgrades]').click();
await page.screenshot({path:'qa/desktop-upgrades.png',fullPage:true});
await page.locator('[data-tab=forge]').click();
await page.locator('#help').click();assert.ok(await page.locator('#help-dialog').isVisible());await page.locator('.close-help').click();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'qa/mobile-prepare.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false,'mobile must not overflow');
assert.equal(await page.locator('.fallback').count(),0,'WebGL scene must initialize');
const summary={errors,save:await page.evaluate(()=>JSON.parse(localStorage.getItem('ember-edge-save-v1'))),mobileOverflow:await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)};
await writeFile('qa/result.json',JSON.stringify(summary,null,2));await browser.close();
assert.deepEqual(errors,[]);console.log('Browser QA passed: rendering, smelt, forge, reload, quench, collection, sale, market, guide and mobile layout.');
